local wow = require("wow")

describe("addon load", function()
	it("loads every file in TOC order", function()
		local w = wow.new()
		w:player("WARRIOR")
		local ns = w:load()
		assert(ns.API and ns.APLDefaults and ns.Tick, "namespace filled")
	end)

	it("boots on login", function()
		local w = wow.new()
		w:player("WARRIOR")
		w:load()
		w:fire("ADDON_LOADED", "KnowYourRotation")
		w:fire("PLAYER_LOGIN")
		w:fire("PLAYER_ENTERING_WORLD", true, false)
		w:advance(1)
		assert(w.ns.booted, "booted")
	end)
end)
